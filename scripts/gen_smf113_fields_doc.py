def table(fields):
    out = ["| Column | Offset | Len | Type | Description |", "|---|---:|---:|---|---|"]
    for f in fields:
        desc = DESC.get(f.name) or missing.append(f.name) or ""
        out.append(f"| `{f.column}` | {f.offset} | {f.length} | {UNITS[f.kind]} | {desc} |")
    return "\n".join(out)


