"""Regenerate docs/smf110-fields.md from a CICS monitoring dictionary.

Usage: .venv/bin/python scripts/gen_smf110_fields_doc.py smf_files/dictionary.bin docs/smf110-fields.md

The smf110_1 columns depend on the site's dictionary (the MCT can exclude fields), so the reference
is built from the dictionary the parser is configured with.
"""

import sys

from smfparser.records import type110 as t
from smfparser.records.header import HEADER_SCHEMA

COMMON = {
"source_file": "Path of the dump file the record came from",
"record_offset": "Byte offset in the file of the record's first segment",
"smf_datetime": "Time and date the record was written (SMFMNTME + SMFMNDTE), local time",
"smf_type": "Record type: 110",
"smf_subtype": "Subtype: 1 (monitoring)",
"smf_sid": "System identifier (SMFMNSID)",
"smf_ssi": "Subsystem identifier: CICS",
"smf_flag": "Header flag byte",
"smfmnrvn": "CICS record version, as hex: `0730` = CICS TS 6.1 record format",
"smfmnprn": "Generic APPLID of the region",
"smfmnspn": "Specific APPLID of the region",
"smfmnjbn": "Job name of the region",
"smfmnuif": "User ID of the region",
"smfmnpdn": "MVS level, e.g. `SP7.2.5`",
"smfmnrst": "Region start date and time (SMFMNRSD + SMFMNRST), local time",
"transaction_index": "Position of the transaction in its SMF record (0-based); with `source_file` and `record_offset`, a unique row key",
"elapsed": "STOP − START in seconds (transaction response time, as EPV's ELAPSED)",
"internal_response": "`elapsed` − `tciowtt_009` (terminal I/O wait) in seconds: response time without waiting for the terminal user, as EPV's INTRESPDUR",
}

KIND = {
"A": "integer (binary count)",
"C": "text (EBCDIC)",
"T": "datetime (STCK)",
"P": "integer (packed decimal)",
"S": "seconds + `_count`",
}


def decoded_as(e: t.DictEntry, hex_fields: frozenset[str]) -> str:
    if e.kind == "A" and e.nickname in t.FLAG_FIELDS:
        return "hex (flags)"
    if e.kind == "C" and e.nickname in hex_fields:
        return "hex (binary)"
    return KIND.get(e.kind, "hex")


def main(dict_path: str, out_path: str) -> None:
    dic = t.Dictionary.load(dict_path)
    schema = t.CicsMonitoringParser(t.ParserOptions({"dictionary": dict_path})).schemas()[t.TABLE]
    missing = [c for c in [*HEADER_SCHEMA, *t.PRODUCT_SCHEMA, *t.DERIVED_SCHEMA] if c not in COMMON]
    if missing:
        sys.exit(f"no description for: {', '.join(missing)}")

    fields = dic.fields
    excluded = [e for e in dic.entries if not e.included]
    out = [
        "# SMF type 110 subtype 1 field reference (CICS performance)",
        "",
        "<!-- Generated by scripts/gen_smf110_fields_doc.py; do not edit by hand. -->",
        "",
        "Table `smf110_1` has one row per CICS transaction, from the performance-class (class 3) monitoring",
        "records. Its columns come from the CICS monitoring dictionary given in `records: {110: {dictionary: …}}`.",
        f"This reference was generated from the dictionary of region `{dic.applid}`: {len(dic.entries)} fields,",
        f"{len(fields)} recorded ({dic.record_length} bytes per transaction) and {len(excluded)} excluded by the MCT.",
        "A region whose MCT records a different set of fields is rejected (see the [user guide](user-guide.md)).",
        "",
        "Column names are `<informal name>_<field id>` in lower case, e.g. `usrcput_008` for DFHTASK S008 USRCPUT.",
        "The informal name alone is not unique (SCUGETCT is both A054 and A105). IBM documents each field in",
        "*CICS TS Monitoring → Performance class data: listing of data fields*; search for the owner and id.",
        "",
        "Decoding by field type:",
        "",
        "| Type | Contents | Output |",
        "|---|---|---|",
        "| A | Binary count, 4 or 8 bytes | integer. Bit-flag fields (TRANFLAG, OTRANFLG, TASKFLAG, TERMINFO) are written as hex |",
        "| C | EBCDIC text | text, trimmed and empty if blank. Control bytes (`x'00'`–`x'3F'`, `x'FF'`) inside the text become blanks, as in EPV. Binary IDs (NETUOWSX, TRNGRPID, RRMSURID, OTSTID) and the Omegamon user fields (OMEGDB2, CANMQ, CANPROD1, CANRES01) are written as hex; the `hex` option adds more |",
        "| T | 8-byte STCK timestamp (UTC) | datetime, converted to local time with the record's time-zone offset unless `local_time: false` |",
        "| P | Packed decimal | integer |",
        "| S | 12-byte clock: 8-byte STCK-format time + flag byte + 24-bit count | two columns: `<name>` in seconds and `<name>_count`, the number of times the clock was started (e.g. dispatches) |",
        "",
        "## Common and region columns",
        "",
        "| Column | Type | Description |",
        "|---|---|---|",
    ]
    for col in [*HEADER_SCHEMA, *t.PRODUCT_SCHEMA]:
        out.append(f"| `{col}` | {schema[col]} | {COMMON[col]} |")
    out += [
        "",
        "## Dictionary fields",
        "",
        "In record order. Offset is from the start of the transaction's performance record.",
        "",
        "| Column | Owner | Field id | Type | Length | Offset | Output |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in fields:
        cols = f"`{e.column}`" + (f", `{e.column}_count`" if e.kind == "S" else "")
        out.append(f"| {cols} | {e.owner} | {e.kind}{e.ident} | {e.kind} | {e.length} | {e.offset} | "
                   f"{decoded_as(e, t.HEX_FIELDS)} |")
    out += [
        "",
        "## Derived columns",
        "",
        "| Column | Type | Description |",
        "|---|---|---|",
    ]
    for col in t.DERIVED_SCHEMA:
        out.append(f"| `{col}` | {schema[col]} | {COMMON[col]} |")
    out += [
        "",
        "## Fields excluded by this dictionary",
        "",
        "These fields exist in CICS but this region's MCT does not record them, so they have no column.",
        "",
        ", ".join(f"{e.owner} {e.kind}{e.ident} {e.nickname}" for e in excluded) or "None.",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
